/** Menu slots: a chapter-opener photo per category and a thumbnail per signature dish. */
export function menuSlots(menu: MenuCategory[]): ImageSlotSpec[] {
  return menu.flatMap((c): ImageSlotSpec[] => [
    {
      kind: "image",
      id: `${c.brandId}.menu.${c.id}.hero`,
      app: c.brandId,
      page: "Landing",
      section: `Menu · ${c.name.en}`,
      width: 1600,
      height: 1000,
      alt: {
        en: `${c.name.en} at ${c.brandId === "covy" ? "COVY" : "Aroma Lounge"}`,
        ar: c.name.ar,
      },
    },
    ...c.items
      .filter((item) => item.imageSlotId || item.photo)
      .map(
        (item): ImageSlotSpec => ({
          kind: "image",
          id: item.imageSlotId ?? `${c.brandId}.menu.${item.id.split(".").pop()}`,
          app: c.brandId,
          page: "Landing",
          section: `Menu · ${c.name.en} · ${item.name.en}`,
          width: 800,
          height: 800,
          alt: item.name,
          ...(item.photo
            ? { src: item.photo, notes: "The client's digital-menu photo (D53)" }
            : {}),
        }),
      ),
  ]);
}

