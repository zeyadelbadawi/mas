// Categories follow the brand guide's "Taste of Everywhere" world tour. Type-only imports: the asset-manifest
// script loads this file with Node's type stripping.
import type { MenuCategory, MenuItem, MenuTag } from "../types";

type Row = [
  slug: string,
  en: string,
  ar: string,
  descEn: string,
  descAr: string,
  price: number,
  tags?: MenuTag[],
];

function items(category: string, rows: Row[]): MenuItem[] {
  return rows.map(([slug, en, ar, descEn, descAr, priceEGP, tags = []]) => ({
    id: `covy.${category}.${slug}`,
    name: { en, ar },
    description: { en: descEn, ar: descAr },
    priceEGP,
    tags,
    ...(tags.includes("signature") ? { imageSlotId: `covy.menu.${slug}` } : {}),
    placeholder: true,
  }));
}

