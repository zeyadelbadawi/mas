#!/usr/bin/env node
// Writes docs/assets/asset-manifest.md from packages/content/src/slots.ts (the designer's checklist).
// Usage: pnpm assets:manifest [--check]   (--check fails if the committed file is out of date)

import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { slots } from "../../packages/content/src/slots.ts";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "../..");
const out = path.join(root, "docs/assets/asset-manifest.md");

const gcd = (a, b) => (b ? gcd(b, a % b) : a);
const ratio = (w, h) => `${w / gcd(w, h)}:${h / gcd(w, h)}`;
const cell = (s) => String(s ?? "").replace(/\|/g, "\\|");
const APPS = [
  ["mas", "MAS (mas.com)"],
  ["covy", "COVY (covy.mas.com)"],
  ["aroma", "Aroma Lounge (aroma.mas.com)"],
];

const images = slots.filter((s) => s.kind === "image");
const sequences = slots.filter((s) => s.kind === "sequence");
const delivered = images.filter((s) => s.src).length;
const rendered = sequences.filter((s) => s.manifestUrl).length;

const lines = [
  "# Asset manifest",
  "",
  "<!-- Generated by `pnpm assets:manifest` from packages/content/src/slots.ts. Do not edit by hand. -->",
  "",
  "Every image and scroll-sequence slot on the three sites. Until a file is delivered, the site shows a placeholder box with the size, ratio and slot ID below.",
  "",
  "**Image delivery:** master as PNG or TIFF (sRGB) at the delivery size or larger, same ratio. We export AVIF/WebP. No text or logos baked into photos.",
  "",
  "**Sequences** are generated by us with MAG, not by the designer (CLAUDE.md rule 4).",
  "",
  `| | Total | Done | Waiting |`,
  `|---|---|---|---|`,
  `| Images (designer) | ${images.length} | ${delivered} | ${images.length - delivered} |`,
  `| Sequences (MAG) | ${sequences.length} | ${rendered} | ${sequences.length - rendered} |`,
  "",
];

for (const [app, title] of APPS) {
  const imgs = images.filter((s) => s.app === app);
  const seqs = sequences.filter((s) => s.app === app);
  if (!imgs.length && !seqs.length) continue;
  lines.push(`## ${title}`, "");
  if (imgs.length) {
    lines.push(
      "### Images",
      "",
      "| Slot ID | Page · section | Delivery size | Ratio | Alt (EN) | Alt (AR) | Status | Notes |",
      "|---|---|---|---|---|---|---|---|",
    );
    for (const s of imgs) {
      lines.push(
        `| \`${s.id}\` | ${cell(s.page)} · ${cell(s.section)} | ${s.width} × ${s.height} px | ${ratio(s.width, s.height)} | ${cell(s.alt.en)} | ${cell(s.alt.ar)} | ${s.src ? "✅ delivered" : "⬜ placeholder"} | ${cell(s.notes)} |`,
      );
    }
    lines.push("");
  }
  if (seqs.length) {
    lines.push(
      "### Scroll sequences",
      "",
      "| Slot ID | Page · section | Frames | Desktop | Mobile | Description | Status | Notes |",
      "|---|---|---|---|---|---|---|---|",
    );
    for (const s of seqs) {
      lines.push(
        `| \`${s.id}\` | ${cell(s.page)} · ${cell(s.section)} | ${s.frameCount} | ${s.desktop.width} × ${s.desktop.height} | ${s.mobile.width} × ${s.mobile.height} | ${cell(s.label.en)} | ${s.manifestUrl ? "✅ rendered" : "⬜ placeholder"} | ${cell(s.notes)} |`,
      );
    }
    lines.push("");
  }
}

const ids = slots.map((s) => s.id);
const dupes = ids.filter((id, i) => ids.indexOf(id) !== i);
if (dupes.length) {
  console.error(`Duplicate slot IDs: ${dupes.join(", ")}`);
  process.exit(1);
}

const markdown = lines.join("\n");
if (process.argv.includes("--check")) {
  let current = "";
  try {
    current = readFileSync(out, "utf8");
  } catch {
    /* missing file counts as stale */
  }
  if (current !== markdown) {
    console.error("docs/assets/asset-manifest.md is out of date. Run: pnpm assets:manifest");
    process.exit(1);
  }
  console.log("Asset manifest is up to date.");
} else {
  writeFileSync(out, markdown);
  console.log(
    `Wrote ${path.relative(root, out)} (${images.length} images, ${sequences.length} sequences)`,
  );
}
