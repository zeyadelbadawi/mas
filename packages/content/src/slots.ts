type App = "mas" | "covy" | "aroma";

export type ImageSlotSpec = {
  kind: "image";
  id: string;
  app: App;
  page: string;
  section: string;
  /** Delivery size in px: 2× the largest rendered size. */
  width: number;
  height: number;
  alt: LocalizedText;
  /** Set when the image is in place (from the designer, or generated by us where D39 allows). */
  src?: string;
  notes?: string;
};

export type SequenceSlotSpec = {
  kind: "sequence";
  id: string;
  app: App;
  page: string;
  section: string;
  frameCount: number;
  desktop: { width: number; height: number };
  mobile: { width: number; height: number };
  label: LocalizedText;
  /** Set when the MAG render has gone through tools/sequences and is on R2. */
  manifestUrl?: string;
  notes?: string;
};

